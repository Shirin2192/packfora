         const images = document.querySelectorAll('.leader-img, .leader-name, .open-info img');
         const popup = document.getElementById('popup');
         const overlay = document.getElementById('overlay');
         const crossIcon = document.getElementById('crossIcon');
         const popupContent = document.getElementById('popupContent');
         
         // Function to open the popup with data
         function openPopup(data) {
             const socialLinks = JSON.parse(data.social || '{}');
         
             let socialHTML = '<div class="social-icons">';
             for (let platform in socialLinks) {
                 socialHTML += `<a href="${socialLinks[platform]}" target="_blank">
                     <img src="assets/img/leaders/linkedin.png" alt="${platform}">
                 </a>`;
             }
             socialHTML += '</div>';
         
             popupContent.innerHTML = `
                 <div class="popup-mob">
                     <h2>${data.title}</h2>
                     <p>${data.para1}</p>
                     <p>${data.para2}</p>
                     <p>${data.para3}</p>
                     <p>${data.para4}</p>
                     <div class="designation">${data.designation}</div>
                     ${socialHTML}
                     <div id="BackBtn" class="back-button">
                         <img src="assets/img/home/intro/Vector.png" alt=""> Go Back
                     </div>
                 </div>
             `;
         
             popup.classList.add('active');
             overlay.classList.add('active');
             document.body.classList.add('popup-open');
         
             // "Go Back" button functionality
             const backBtn = document.getElementById('BackBtn');
             if (backBtn) {
                 backBtn.addEventListener('click', (e) => {
                     e.stopPropagation();
                     closePopup();
                 });
             }
         }
         
         // Function to close the popup
         function closePopup() {
             popup.classList.remove('active');
             overlay.classList.remove('active');
             document.body.classList.remove('popup-open');
         }
         
         // Add click event to each interactive element
         images.forEach(image => {
             image.addEventListener('click', (e) => {
                 e.preventDefault(); // Prevent anchor default behavior
                 e.stopPropagation();
         
                 const parent = image.closest('.leader');
                 const mainImage = parent.querySelector('.leader-img');
         
                 const data = {
                     title: mainImage.getAttribute('data-title'),
                     para1: mainImage.getAttribute('data-para1'),
                     para2: mainImage.getAttribute('data-para2'),
                     para3: mainImage.getAttribute('data-para3'),
                     para4: mainImage.getAttribute('data-para4'),
                     designation: mainImage.getAttribute('data-designation'),
                     social: mainImage.getAttribute('data-social')
                 };
         
                 openPopup(data);
             });
         });
         
         // Close popup when clicking on overlay
         overlay.addEventListener('click', closePopup);
         
         // Close popup when clicking on cross icon
         crossIcon.addEventListener('click', (e) => {
             e.stopPropagation();
             closePopup();
         });
         
         // Optional: Click outside popup content to close
         document.addEventListener('click', (e) => {
             if (popup.classList.contains('active') &&
                 !popup.contains(e.target) &&
                 !overlay.contains(e.target)) {
                 closePopup();
             }
         });
